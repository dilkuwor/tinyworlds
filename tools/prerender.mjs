/**
 * prerender.mjs - Bake the homepage and search/share tags into the HTML.
 *
 *   node tools/prerender.mjs <site-dir>
 *
 * Runs at image build time (see Dockerfile), on a copy of the site:
 *  - fills the homepage shelf and world sections using the same templates
 *    the browser uses (render.js), from the same data (scenes.js)
 *  - writes description, canonical, Open Graph and Twitter tags into the
 *    <head> of the homepage and every world page, plus structured data on
 *    the homepage
 *  - writes sitemap.xml
 * Safe to run more than once: generated parts are replaced, not repeated.
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const root = path.resolve(process.argv[2] || '.');
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');
const write = (f, s) => fs.writeFileSync(path.join(root, f), s);

// Load the world list and the templates exactly as the browser would
const ctx = vm.createContext({});
vm.runInContext(`${read('scenes.js')}\n${read('render.js')}\n
  this.out = { TINY_WORLDS, TW_SITE, twShelfItem, twWorldSection, twEscape };`, ctx);
const { TINY_WORLDS, TW_SITE, twShelfItem, twWorldSection, twEscape: esc } = ctx.out;

/** Put generated markup inside an (empty or previously filled) element, between markers. */
function fill(html, openTagRe, inner, label) {
  const re = new RegExp(`(${openTagRe.source})(?:\\s*<!-- gen -->[\\s\\S]*?<!-- /gen -->)?\\s*(</(?:nav|div)>)`);
  if (!re.test(html)) throw new Error(`prerender: couldn't find ${label}`);
  return html.replace(re, (_, open, close) => `${open}<!-- gen -->\n${inner}\n      <!-- /gen --></${close.slice(2)}`);
}

function headTags({ title, description, url, image, alt, jsonLd }) {
  const lines = [
    `<meta name="description" content="${esc(description)}">`,
    `<link rel="canonical" href="${url}">`,
    `<meta property="og:type" content="website">`,
    `<meta property="og:site_name" content="${esc(TW_SITE.name)}">`,
    `<meta property="og:title" content="${esc(title)}">`,
    `<meta property="og:description" content="${esc(description)}">`,
    `<meta property="og:url" content="${url}">`,
    `<meta property="og:image" content="${image}">`,
    `<meta property="og:image:width" content="1200">`,
    `<meta property="og:image:height" content="630">`,
    `<meta property="og:image:alt" content="${esc(alt)}">`,
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${esc(title)}">`,
    `<meta name="twitter:description" content="${esc(description)}">`,
    `<meta name="twitter:image" content="${image}">`
  ];
  if (jsonLd) lines.push(`<script type="application/ld+json">${JSON.stringify(jsonLd).replace(/</g, '\\u003c')}</script>`);
  return `  <!-- seo:start (generated by tools/prerender.mjs) -->\n${lines.map(l => `  ${l}`).join('\n')}\n  <!-- seo:end -->\n`;
}

function withHead(html, tags) {
  html = html
    .replace(/  <!-- seo:start[\s\S]*?<!-- seo:end -->\n/, '')
    .replace(/^\s*<meta name="description"[^>]*>\n/m, '');
  return html.replace('</head>', `${tags}</head>`);
}

// ---------- Homepage ----------
const homeUrl = `${TW_SITE.url}/`;
let home = read('index.html');
home = fill(home, /<nav id="shelf-list"[^>]*>/, TINY_WORLDS.map(w => `      ${twShelfItem(w)}`).join('\n'), 'the shelf');
home = fill(home, /<div id="world-list"[^>]*>/, TINY_WORLDS.map((w, i) => `    ${twWorldSection(w, i)}`).join('\n'), 'the world list');
home = withHead(home, headTags({
  title: TW_SITE.title,
  description: TW_SITE.description,
  url: homeUrl,
  image: `${TW_SITE.url}/og/home.jpg`,
  alt: 'Tiny Worlds: a collage of small animated scenes',
  jsonLd: {
    '@context': 'https://schema.org',
    '@graph': [
      { '@type': 'WebSite', name: TW_SITE.name, url: homeUrl, description: TW_SITE.description },
      {
        '@type': 'ItemList',
        name: 'The worlds',
        itemListElement: TINY_WORLDS.map((w, i) => ({
          '@type': 'ListItem', position: i + 1, url: `${TW_SITE.url}/${w.slug}/`, name: w.title
        }))
      }
    ]
  }
}));
write('index.html', home);

// ---------- Each world ----------
for (const w of TINY_WORLDS) {
  const file = `${w.slug}/index.html`;
  let html = read(file);
  const title = (html.match(/<title>([^<]*)<\/title>/) || [])[1] || `${w.title} · ${TW_SITE.name}`;
  html = withHead(html, headTags({
    title,
    description: w.description,
    url: `${TW_SITE.url}/${w.slug}/`,
    image: `${TW_SITE.url}/og/${w.slug}.jpg`,
    alt: `${w.title}, one of the Tiny Worlds`
  }));
  write(file, html);
}

// ---------- Sitemap ----------
const today = new Date().toISOString().slice(0, 10);
const urls = [homeUrl, ...TINY_WORLDS.map(w => `${TW_SITE.url}/${w.slug}/`)];
write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(u => `  <url><loc>${u}</loc><lastmod>${today}</lastmod></url>`).join('\n')}
</urlset>
`);

console.log(`prerender: homepage + ${TINY_WORLDS.length} worlds, sitemap with ${urls.length} URLs`);
